#!/usr/bin/env bash
# SessionStart hook «Второй мозг» — подгружает ядро в контекст КАЖДОЙ сессии
# Claude Code и напоминает записать итог в конце. stdout попадает в контекст.
#
# Путь к папке _BRAIN подставляет установщик (__BRAIN_DIR__). cat-загрузка
# устойчива к путям с пробелами и облачным папкам (в отличие от @import).
set -euo pipefail

BRAIN="__BRAIN_DIR__"

# Ядро грузится в КАЖДУЮ сессию, поэтому у него есть потолок: раздутый STACK.md
# незаметно съедает окно контекста и деньги. Файл длиннее лимита обрезается по
# строкам, и хук честно говорит об этом — это сигнал разнести файл по заметкам.
MAX_PER_FILE="${SB_HOOK_MAX_BYTES:-20000}"    # байт на файл
MAX_TOTAL="${SB_HOOK_MAX_TOTAL:-60000}"       # байт на всё ядро

# Vault недоступен (например, облако ещё не синхронизировалось) — тихо выходим,
# чтобы не ронять старт сессии.
[ -d "$BRAIN" ] || exit 0

echo "# Второй мозг — ядро (автозагрузка SessionStart)"
echo
echo "Контекст из твоего хранилища. Используй как фон, не дублируй дословно в ответах."
echo "**В конце содержательной сессии — запиши память обратно:** ОБНОВИ \`_BRAIN/hot.md\` (3–6 строк: над чем работали, следующий шаг, тронутые файлы); если был итог/решение/находка — допиши в \`_BRAIN/Выводы\` / \`_BRAIN/Решения\` / \`_BRAIN/Заметки\`. Делай это без лишних вопросов, коротко отчитываясь «сохранил в …». Это и есть «второй мозг помнит»."
echo

spent=0
for f in hot.md INDEX.md STATE.md STACK.md; do
  p="$BRAIN/$f"
  [ -f "$p" ] || continue

  left=$((MAX_TOTAL - spent))
  if [ "$left" -le 0 ]; then
    echo "---"
    echo "## _BRAIN/$f — НЕ ЗАГРУЖЕН: ядро уже превысило ${MAX_TOTAL} байт."
    echo "Прочитай файл сам, если он нужен: \`$p\`"
    echo
    continue
  fi
  limit=$MAX_PER_FILE
  [ "$left" -lt "$limit" ] && limit=$left

  size=$(LC_ALL=C wc -c < "$p" | tr -d ' ')
  echo "---"
  echo "## _BRAIN/$f"
  echo
  if [ "$size" -le "$limit" ]; then
    cat "$p"
    spent=$((spent + size))
  else
    # режем по строкам, чтобы не рвать UTF-8 посередине символа
    LC_ALL=C awk -v lim="$limit" '{ n += length($0) + 1; if (n > lim) exit; print }' "$p"
    spent=$((spent + limit))
    echo
    echo "> ⚠️ Файл обрезан: ${size} байт при лимите ${limit}. Загружено начало."
    echo "> Полный файл — \`$p\`. Разнеси старое по \`_BRAIN/Заметки/\` и \`_BRAIN/Архив/\`, чтобы ядро осталось лёгким."
  fi
  echo
done
